/* ---------- Анимированный фон шапки ---------- */
const canvas = document.getElementById('hero-canvas');
if (canvas) {
    const ctx = canvas.getContext('2d');
    let W = 0, H = 0, t = 0, particles = [];

    function resize() {
        W = canvas.width = canvas.offsetWidth;
        H = canvas.height = canvas.offsetHeight;
        particles = Array.from({ length: 40 }, () => ({
            x: Math.random() * W,
            y: Math.random() * H,
            s: Math.random() * 1.5 + 0.5,
            v: Math.random() * 0.35 + 0.1,
            a: Math.random() * 0.35 + 0.1
        }));
    }
    resize();
    window.addEventListener('resize', resize);

    function draw() {
        t += 1;
        ctx.clearRect(0, 0, W, H);

        const horizon = H * 0.55;
        const vp = W / 2;

        // перспективная сетка
        ctx.strokeStyle = 'rgba(74, 158, 255, 0.13)';
        ctx.lineWidth = 1;
        for (let i = -12; i <= 12; i++) {
            ctx.beginPath();
            ctx.moveTo(vp + i * 8, horizon);
            ctx.lineTo(vp + i * (W / 7), H);
            ctx.stroke();
        }

        const offset = (t * 0.6) % 60;
        for (let i = 0; i < 20; i++) {
            const p = (i * 60 - offset) / 60;
            if (p < 0) continue;
            const y = horizon + Math.pow(p, 2.2) * (H - horizon) * 0.9;
            if (y > H) continue;
            ctx.globalAlpha = Math.min(1, p * 0.5);
            ctx.beginPath();
            ctx.moveTo(0, y);
            ctx.lineTo(W, y);
            ctx.stroke();
        }
        ctx.globalAlpha = 1;

        // частицы
        particles.forEach(p => {
            p.y -= p.v;
            if (p.y < -5) { p.y = H + 5; p.x = Math.random() * W; }
            ctx.fillStyle = `rgba(230, 230, 230, ${p.a})`;
            ctx.fillRect(p.x, p.y, p.s, p.s * 2);
        });

        requestAnimationFrame(draw);
    }
    draw();
}
