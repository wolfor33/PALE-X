/* Плавное появление при скролле (без IntersectionObserver) */
function revealOnScroll() {
    const vh = window.innerHeight;
    document.querySelectorAll('.section:not(.visible), .reveal:not(.visible)').forEach(el => {
        const rect = el.getBoundingClientRect();
        if (rect.top < vh * 0.9 && rect.bottom > 0) {
            el.classList.add('visible');
        }
    });

    // Верхняя панель появляется после шапки
    const topbar = document.getElementById('topbar');
    if (topbar) {
        topbar.classList.toggle('show', window.scrollY > vh * 0.75);
    }
}

window.addEventListener('scroll', revealOnScroll, { passive: true });
window.addEventListener('resize', revealOnScroll);

revealOnScroll();
window.addEventListener('load', revealOnScroll);
setTimeout(revealOnScroll, 300);

